// Builds the in-app copies of the notes (guide/*.html) and their contents list (data/notes-toc.json)
// from the sources in notes/ (also published on claude.ai). Run via `npm run stamp`; a test checks they are fresh.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PAGES = {
  'system-notes.html': { other: 'convention-card.html', otherTitle: 'Convention card' },
  'convention-card.html': { other: 'system-notes.html', otherTitle: 'System notes' },
};
// claude.ai addresses of the published copies → the in-app pages.
const LINKS = {
  'https://claude.ai/artifact/NrdCttHcwDpCv83CsLGpfd': 'system-notes.html',
  'https://claude.ai/artifact/E899gpbkkmxzkihMgyTzC5': 'convention-card.html',
};
// Same as index.html: apply the theme chosen in the app before first paint.
const THEME = "<script>try{var t=JSON.parse(localStorage.getItem('bc:theme')||'{}').theme;if(t==='light'||t==='dark')document.documentElement.dataset.theme=t}catch(e){}</script>";
const BAR_CSS = `<style>
body{margin:0}
.appbar{position:sticky;top:0;z-index:20;display:flex;justify-content:space-between;gap:12px;padding:calc(env(safe-area-inset-top,0px) + 10px) 16px 10px;background:var(--bg);border-bottom:1px solid var(--rule);font-weight:600}
.appbar a{color:var(--accent);text-decoration:none}
.appbar + *{margin-top:10px}
</style>`;

export function buildPage(name, source) {
  let html = source;
  for (const [url, page] of Object.entries(LINKS)) html = html.split(url).join(page);
  const cut = html.indexOf('</style>') + '</style>'.length;
  const { other, otherTitle } = PAGES[name];
  return [
    '<!doctype html>',
    '<html lang="en">',
    '<head>',
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">',
    '<meta name="theme-color" content="#1d6a49">',
    `<!-- Generated by tools/build-notes.mjs from notes/${name}. Edit the source, then run npm run stamp. -->`,
    THEME,
    html.slice(0, cut).trim(),
    BAR_CSS,
    '</head>',
    '<body>',
    `<nav class="appbar" aria-label="Bridge Coach"><a href="../">← Bridge Coach</a><a href="${other}">${otherTitle}</a></nav>`,
    html.slice(cut).trim(),
    '</body>',
    '</html>',
    '',
  ].join('\n');
}

// The notes' top-level sections, for the Notes tab: [{ id, title, tier, part }].
export function contents(source) {
  const out = [];
  let part = '';
  for (const m of source.matchAll(/<p class="part" id="[^"]+">([^<]*)<\/p>|<h2 id="([^"]+)">([\s\S]*?)<\/h2>/g)) {
    if (m[1] !== undefined) { part = m[1].trim(); continue; }
    const [, , id, inner] = m;
    out.push({
      id,
      title: inner.replace(/<span class="tier[^"]*">[^<]*<\/span>/g, '').replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim(),
      tier: (inner.match(/class="tier[^"]*">([^<]*)</) ?? [])[1] ?? '',
      part,
    });
  }
  return out;
}

// Every section and subsection id: the places a rule's "Read more" link may point to.
export const anchors = (source) => [...source.matchAll(/<h[23] id="([^"]+)"/g)].map((m) => m[1]);

export function outputs(root) {
  const out = {};
  for (const name of Object.keys(PAGES)) out[`guide/${name}`] = buildPage(name, readFileSync(join(root, 'notes', name), 'utf8'));
  const notes = readFileSync(join(root, 'notes/system-notes.html'), 'utf8');
  out['data/notes-toc.json'] = `${JSON.stringify(contents(notes), null, 1)}\n`;
  out['data/notes-anchors.json'] = `${JSON.stringify(anchors(notes), null, 1)}\n`;
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const root = fileURLToPath(new URL('..', import.meta.url));
  mkdirSync(join(root, 'guide'), { recursive: true });
  for (const [path, text] of Object.entries(outputs(root))) writeFileSync(join(root, path), text);
  console.log('guide/ rebuilt from notes/');
}
